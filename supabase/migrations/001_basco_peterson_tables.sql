-- Isolated per-client company/contact tables for the email-waterfall MCP.
-- Applied to campaignintelligence (azpapwtnrbzywlnxxecz).
-- Companies upsert on domain. Contacts UNIQUE (domain, email) for PostgREST ON CONFLICT.

CREATE TABLE IF NOT EXISTS public.basco_companies (
  domain text PRIMARY KEY,
  company_name text,
  source text,
  in_shovels boolean,
  in_maps_icp boolean,
  permit_count integer,
  place text,
  address_city text,
  address_state text,
  employee_range text,
  shovels_email text,
  shovels_name text,
  dm_lookup_status text,
  email_source_tier text,
  dm_source_tier text,
  source_tier jsonb,
  website text,
  client_tag text NOT NULL DEFAULT 'basco',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT basco_companies_client_tag_check CHECK (client_tag = 'basco')
);

CREATE TABLE IF NOT EXISTS public.basco_contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain text NOT NULL,
  first_name text,
  last_name text,
  job_title text,
  job_level text,
  email text,
  email_status text,
  cellphone text,
  linkedin_url text,
  contact_city text,
  contact_state text,
  source_tool text,
  source_tier text,
  source_url text,
  confidence double precision,
  place_id text,
  client_tag text NOT NULL DEFAULT 'basco',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT basco_contacts_client_tag_check CHECK (client_tag = 'basco'),
  CONSTRAINT basco_contacts_domain_email_key UNIQUE (domain, email)
);

